#!/usr/bin/env python3
"""Generate the amalgamated single-header / single-source builds.

Edit include/wccs.h or src/wccs.c, then run:

    python tools/amalgamate.py

Outputs (checked in, so a reviewer can read the whole algorithm in one file):

    single_header/wccs.h   header-only; define WCCS_IMPLEMENTATION once
    single_source/wccs.c   self-contained translation unit

The generator is deliberately dumb: it concatenates the two authoritative
files and inserts the implementation inside the existing `extern "C"` block,
so C++ consumers get the correct linkage without extra macros.
"""
from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HEADER = ROOT / "include" / "wccs.h"
SOURCE = ROOT / "src" / "wccs.c"
OUT_HEADER = ROOT / "single_header" / "wccs.h"
OUT_SOURCE = ROOT / "single_source" / "wccs.c"

BANNER = """\
/* WCCS amalgamated build -- generated by tools/amalgamate.py.
 * DO NOT EDIT: edit include/wccs.h or src/wccs.c, then regenerate.
 *
 * Header-only use (define the macro in exactly one translation unit):
 *     #define WCCS_IMPLEMENTATION
 *     #include "wccs.h"
 *
 * Single-source use:
 *     cc -O2 single_source/wccs.c your_app.c
 */

/* The amalgamation is a drop-in static build. Define WCCS_BUILD_DLL before
 * including it if you really need to export the symbols from a DLL. */
#if !defined(WCCS_STATIC) && !defined(WCCS_BUILD_DLL)
#  define WCCS_STATIC 1
#endif
"""

CPP_TAIL = '#ifdef __cplusplus\n}\n#endif'


def implementation_body() -> str:
    text = SOURCE.read_text(encoding="utf-8")
    text = text.replace('#include "wccs.h"\n', "", 1)
    if '#include "wccs.h"' in text:
        raise SystemExit("unexpected second include of wccs.h in src/wccs.c")
    return text


def insert_before_cpp_close(header: str, chunk: str) -> str:
    idx = header.rindex(CPP_TAIL)
    return header[:idx] + chunk + "\n" + header[idx:]


def main() -> None:
    header = HEADER.read_text(encoding="utf-8")
    body = implementation_body()

    OUT_HEADER.parent.mkdir(parents=True, exist_ok=True)
    OUT_SOURCE.parent.mkdir(parents=True, exist_ok=True)

    header_only = insert_before_cpp_close(
        header,
        "#ifdef WCCS_IMPLEMENTATION\n"
        + body
        + "#endif /* WCCS_IMPLEMENTATION */\n",
    )
    OUT_HEADER.write_text(BANNER + "\n" + header_only, encoding="utf-8")

    single = insert_before_cpp_close(header, body)
    OUT_SOURCE.write_text(BANNER + "\n" + single, encoding="utf-8")

    print("wrote %s (%d lines)" % (
        OUT_HEADER.relative_to(ROOT), len(header_only.splitlines())))
    print("wrote %s (%d lines)" % (
        OUT_SOURCE.relative_to(ROOT), len(single.splitlines())))


if __name__ == "__main__":
    main()
